"""Generate BibTeX from the project's audited bibliography.

Reads `bibliography.json` and writes `shadow_mirror_sources.bib`.

Two collections are emitted and kept separate on purpose:

  * `manuscript_references_verified_session_14` - the 105 manuscript references
    confirmed against a live source, every one carrying a resolvable identifier.
  * `monograph_bibliography_audited_session_6`  - the earlier monograph audit.

Entries whose citation appears in a paper's reference list but *not* in the
verified set are reported on stderr rather than silently emitted as verified;
see OW-9 in APPENDIX_OUTSTANDING_WORK.md.
"""
import json
import re
import sys
import unicodedata

SRC = "bibliography.json"
DST = "shadow_mirror_sources.bib"


def ascii_key(s):
    s = unicodedata.normalize("NFKD", s)
    return "".join(c for c in s if c.isalnum())


def first_author(text):
    """Best-effort surname of the first author, for the citation key."""
    m = re.match(r"\s*([A-Z]\.\s*)+([A-Z][\wÀ-ɏ'-]+)", text)
    if m:
        return m.group(2)
    m = re.match(r"\s*([A-Z][\wÀ-ɏ'-]+),", text)
    if m:
        return m.group(1)
    m = re.match(r"\s*(?:Regulation|Law|Supreme|Ministerial)", text)
    if m:
        return "Statute"
    m = re.match(r"\s*([A-Z][\wÀ-ɏ'-]+)", text)
    return m.group(1) if m else "Anon"


def get_title(text):
    """Prefer a quoted title, then an italicised one."""
    m = re.search(r'"([^"]{6,})"', text)
    if m:
        return m.group(1).rstrip(".")
    m = re.search(r"\*([^*]{6,})\*", text)
    if m:
        return m.group(1).rstrip(".")
    # fall back to the span after the author block
    m = re.match(r"^(?:[A-Z]\.\s*|[A-Z][\w'-]+[,.]?\s*|and\s+|et al\.\s*)+(.{10,120}?)\.", text)
    return (m.group(1) if m else text[:110]).strip()


def get_year(text, fallback=None):
    yrs = re.findall(r"\b(19[5-9]\d|20[0-2]\d)\b", text)
    return yrs[-1] if yrs else (str(fallback) if fallback else "")


def esc(s):
    return s.replace("\\", r"\textbackslash{}").replace("&", r"\&") \
            .replace("%", r"\%").replace("_", r"\_").replace("#", r"\#")


def emit(entry_text, ident, year, key, verified, extra=None):
    doi = arxiv = url = ""
    m = re.search(r"(?:DOI:\s*|doi\.org/)(10\.\S+)", entry_text)
    if m:
        # a DOI may legitimately contain periods, so trim only trailing punctuation
        doi = m.group(1).rstrip(".,;:)]}")
    m = re.search(r"arXiv:\s*(\d{4}\.\d{4,5})", entry_text)
    if m:
        arxiv = m.group(1)
    m = re.search(r"(https?://\S+)", entry_text)
    if m:
        url = m.group(1).rstrip(".,)")

    kind = "@article" if doi else ("@misc" if (arxiv or url) else "@misc")
    lines = ["%s{%s," % (kind, key)]
    lines.append("  author       = {%s}," % esc(re.split(r'["*]', entry_text)[0].strip(" .")))
    lines.append("  title        = {{%s}}," % esc(get_title(entry_text)))
    if year:
        lines.append("  year         = {%s}," % year)
    if doi:
        lines.append("  doi          = {%s}," % doi)
    if arxiv:
        lines.append("  eprint       = {%s}," % arxiv)
        lines.append("  archiveprefix= {arXiv},")
    if url and not doi:
        lines.append("  url          = {%s}," % esc(url))
    if ident:
        lines.append("  note         = {%s}," % esc(ident))
    lines.append("  keywords     = {%s}," % ("verified" if verified else "unverified"))
    if extra:
        lines.append("  annote       = {%s}," % esc(extra))
    lines.append("  abstract     = {%s}" % esc(" ".join(entry_text.split())))
    lines.append("}")
    return "\n".join(lines)


def main():
    b = json.load(open(SRC, encoding="utf8"))
    verified = b["manuscript_references_verified_session_14"]
    monograph = b["monograph_bibliography_audited_session_6"]

    out = [
        "%% Shadow Mirror - project bibliography",
        "%% Generated by papers/make_bibliography.py from bibliography.json",
        "%%",
        "%%%% Collection 1: %d manuscript references confirmed against a live source" % len(verified),
        "%%               (Session 14). Every entry carries a resolvable identifier.",
        "%%%% Collection 2: %d entries from the Session 6 monograph audit." % len(monograph),
        "%%",
        "%% Nine references appear in the P1/P2 reference lists but not in collection 1;",
        "%% they were added in Session 15, after the verification pass. See OW-9.",
        "",
        "%% " + "=" * 72,
        "%% Collection 1 - verified manuscript references",
        "%% " + "=" * 72,
        "",
    ]

    seen = {}
    for e in verified:
        text, paper, n = e["entry"], e["paper"], e["n"]
        year = get_year(text)
        base = "%s%s" % (ascii_key(first_author(text)), year or "n")
        seen[base] = seen.get(base, 0) + 1
        key = base if seen[base] == 1 else "%s%s" % (base, chr(ord('a') + seen[base] - 2))
        out.append(emit(text, e.get("identifier", ""), year, key, e.get("verified", False),
                        extra="%s reference [%d]" % (paper, n)))
        out.append("")

    out += ["%% " + "=" * 72,
            "%% Collection 2 - Session 6 monograph audit",
            "%% " + "=" * 72, ""]

    for e in monograph:
        text = e["text"]
        year = get_year(text, e.get("year"))
        base = "mono%s%s" % (ascii_key(first_author(text)), year or "n")
        seen[base] = seen.get(base, 0) + 1
        key = base if seen[base] == 1 else "%s%s" % (base, chr(ord('a') + seen[base] - 2))
        ident = e.get("doi") or e.get("arxiv") or e.get("url") or ""
        out.append(emit(text, ("DOI: " + ident) if e.get("doi") else ident,
                        year, key, True))
        out.append("")

    with open(DST, "w", encoding="utf8") as f:
        f.write("\n".join(out))

    print("wrote %s" % DST)
    print("  collection 1 (verified manuscript refs): %d" % len(verified))
    print("  collection 2 (monograph audit)         : %d" % len(monograph))
    print("  total entries                          : %d" % (len(verified) + len(monograph)))
    print("  entries without resolvable identifier  : %s"
          % b["counts"].get("entries_without_resolvable_identifier"))


if __name__ == "__main__":
    main()
